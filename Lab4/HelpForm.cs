using System.Drawing;
using System.Windows.Forms;

namespace Lab4
{
    /// <summary>Справочная система: окно с текстом справки (F1).</summary>
    public class HelpForm : Form
    {
        public HelpForm()
        {
            Text = "Справка";
            Size = new Size(720, 560);
            StartPosition = FormStartPosition.CenterParent;
            ShowInTaskbar = false;

            Controls.Add(new TextBox
            {
                Dock = DockStyle.Fill,
                Multiline = true,
                ReadOnly = true,
                ScrollBars = ScrollBars.Vertical,
                BackColor = Color.White,
                Font = new Font("Segoe UI", 10F),
                Text = HelpText.Replace("\n", "\r\n")
            });
        }

        private const string HelpText =
@"ЛАБОРАТОРНАЯ РАБОТА № 4

Программа состоит из трёх вкладок — по числу частей задания. Каждую команду можно выполнить кнопкой на вкладке или через меню. Результаты выводятся в текстовое поле вкладки.

1. ФАЙЛОВЫЕ ОПЕРАЦИИ (4.2.1)
В текущем каталоге программы создаётся структура TESTDIR\S1\S2\S4 и TESTDIR\S1\S3\S5.
Пункты 1–12 выполняются по порядку:
 1 — создать структуру каталогов, перейти в S1, показать дерево;
 2 — создать file1.txt со строкой «Текстовая строка»;
 3 — прочитать файл целиком;
 4 — прочитать 8 байт, начиная с 5-го;
 5 — дописать «Дополнительная строка» (с блокировкой участка файла);
 6 — поставить атрибуты «только чтение» и «скрытый» и попробовать удалить файл;
 7 — снять «скрытый», изменить дату создания;
 8 — переименовать в file2.txt;
 9 — переместить в S2, скопировать в S3, показать содержимое S1–S3;
10 — установить метку диска LABEL;
11 — прочитать метку и сравнить с LABEL;
12 — изменить или стереть метку средствами Windows и проверить ещё раз.
Кнопка «Выполнить п.1–9» выполняет файловые пункты подряд, «Удалить TESTDIR» убирает всё созданное.

Диск для п.10–12 выбирается в списке слева. Чтобы изменить метку системного диска C:, программу нужно запустить от имени администратора. Удобнее взять флешку.
П.12: откройте Проводник → правая кнопка на диске → Свойства, измените метку (или очистите поле, чтобы её стереть), затем нажмите ОК в окне программы.

2. ПАМЯТЬ (4.2.2)
 1) Информация о системе — процессор, число ядер, размер страницы.
 2) Состояние памяти — физическая и виртуальная память, память процесса.
 3) Виртуальное адресное пространство — модули процесса и функция VirtualQuery для нескольких адресов.

3. БУФЕР ОБМЕНА (4.2.3)
Список форматов обновляется раз в секунду (флажок «Таймер»). Скопируйте что-нибудь в другой программе — текст в Блокноте или Word, картинку в Paint, файл в Проводнике — и посмотрите, как меняется список.
Пометка «(автопреобразование)» означает, что данные в этом формате не записаны, но система преобразует их по запросу.

ОШИБКИ
Если операция не удалась (нет файла, нет прав, диск защищён от записи, буфер занят другой программой), программа показывает окно с описанием ошибки.";
    }
}
